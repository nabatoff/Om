/**
 * Парсит HTML-экспорт Excel (Без названия.xls) → supabase/seed/ens_tru_codes.sql
 * Usage: node scripts/parse-ens-tru-xls.mjs [path-to-xls]
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const defaultPath = join(process.env.USERPROFILE || '', 'Desktop', 'Без названия.xls');
const xlsPath = process.argv[2] || defaultPath;

const CODE_RE = /\d{6}\.\d{3}\.\d{6}/g;

function stripHtml(html) {
  return html
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .trim();
}

function sqlEscape(s) {
  return s.replace(/'/g, "''");
}

const raw = readFileSync(xlsPath, 'utf8');
const rowRe = /<tr>([\s\S]*?)<\/tr>/gi;
const cellRe = /<td[^>]*>([\s\S]*?)<\/td>/gi;

let currentCategory = '';
const rows = [];
let m;

while ((m = rowRe.exec(raw)) !== null) {
  const cells = [];
  let cm;
  while ((cm = cellRe.exec(m[1])) !== null) {
    cells.push(stripHtml(cm[1]));
  }
  if (cells.length === 0) continue;

  if (cells.length === 1 && /^\d+\.\s/.test(cells[0])) {
    currentCategory = cells[0].replace(/\s+/g, ' ').trim();
    continue;
  }

  if (cells.length < 3) continue;
  const num = cells[0].replace(/\D/g, '');
  const name = cells[1].replace(/\s+/g, ' ').trim();
  const codesBlock = cells[2];
  if (!name || !num) continue;
  if (name === 'Наименование' || name.includes('номенклатурному справочнику')) continue;

  const codes = codesBlock.match(CODE_RE) || [];
  for (const code of codes) {
    rows.push({ code, name, category: currentCategory || 'Без категории' });
  }
}

const byKey = new Map();
for (const r of rows) {
  const key = `${r.code}\0${r.name}\0${r.category}`;
  if (!byKey.has(key)) byKey.set(key, r);
}

const unique = [...byKey.values()];
const uniqueCodes = new Set(unique.map((r) => r.code));
console.log(
  `Parsed ${unique.length} entries (${uniqueCodes.size} unique codes) from ${rows.length} raw matches`,
);

const lines = unique.map(
  (r) =>
    `  ('${sqlEscape(r.code)}', '${sqlEscape(r.name)}', '${sqlEscape(r.category)}')`,
);

const sql = `-- Auto-generated by scripts/parse-ens-tru-xls.mjs (${unique.length} codes)
INSERT INTO public.crm_ens_tru_codes (code, name, category)
VALUES
${lines.join(',\n')}
ON CONFLICT (code, name) DO UPDATE SET
  category = EXCLUDED.category;
`;

const outDir = join(__dirname, '..', 'supabase', 'seed');
mkdirSync(outDir, { recursive: true });
const outPath = join(outDir, 'ens_tru_codes.sql');
writeFileSync(outPath, sql, 'utf8');
console.log(`Wrote ${outPath}`);
