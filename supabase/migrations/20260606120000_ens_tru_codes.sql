CREATE OR REPLACE FUNCTION public.normalize_ens_tru_code(p_raw text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  v text := trim(coalesce(p_raw, ''));
  m text[];
BEGIN
  v := regexp_replace(v, ';+\s*$', '', 'g');
  m := regexp_match(v, '(\d{6}\.\d{3}\.\d{6})');
  IF m IS NULL THEN
    RETURN NULL;
  END IF;
  RETURN m[1];
END;
$$;

CREATE OR REPLACE FUNCTION public.check_ens_tru_codes(p_codes text[])
RETURNS TABLE (
  input_code text,
  found boolean,
  name text,
  category text
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_code text;
  v_norm text;
  v_seen text[] := ARRAY[]::text[];
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Unauthorized' USING ERRCODE = '28000';
  END IF;
  IF public.is_admin() THEN
    RAISE EXCEPTION 'Forbidden' USING ERRCODE = '42501';
  END IF;

  IF p_codes IS NULL OR array_length(p_codes, 1) IS NULL THEN
    RETURN;
  END IF;

  FOREACH v_code IN ARRAY p_codes LOOP
    v_norm := public.normalize_ens_tru_code(v_code);
    IF v_norm IS NULL THEN
      CONTINUE;
    END IF;
    IF v_norm = ANY (v_seen) THEN
      CONTINUE;
    END IF;
    v_seen := array_append(v_seen, v_norm);

    RETURN QUERY
    SELECT
      v_norm AS input_code,
      (e.code IS NOT NULL) AS found,
      e.name,
      e.category
    FROM (SELECT 1) AS dummy
    LEFT JOIN public.crm_ens_tru_codes e ON e.code = v_norm;
  END LOOP;
END;
$$;

